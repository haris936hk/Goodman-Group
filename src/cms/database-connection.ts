/** Remote databases always use verified TLS; loopback databases may use plaintext. */
export function cmsDatabasePoolConfig(connectionString: string): PoolConfig {
  const url = new URL(connectionString);
  if (!["postgres:", "postgresql:"].includes(url.protocol) || !url.hostname) {
    throw new Error("CMS requires a PostgreSQL DATABASE_URL.");
  }
  const local = ["localhost", "127.0.0.1", "[::1]"].includes(url.hostname);
  for (const key of ["ssl", "sslcert", "sslkey", "sslrootcert", "sslmode", "uselibpqcompat"]) {
    if (url.searchParams.has(key)) {
      const value = url.searchParams.get(key);
      if (key !== "sslmode" || !["require", "verify-ca", "verify-full"].includes(value ?? "")) {
        throw new Error("DATABASE_URL contains an unsupported TLS parameter.");
      }
      url.searchParams.delete(key);
    }
  }
  const hostname = url.hostname.toLowerCase();
  const supabase = hostname.endsWith(".supabase.co") || hostname.endsWith(".pooler.supabase.com");
  return {
    connectionString: url.toString(),
    ssl: local ? false : supabase ? { ca: SUPABASE_ROOT_CA, rejectUnauthorized: true } : { rejectUnauthorized: true },
  };
}
